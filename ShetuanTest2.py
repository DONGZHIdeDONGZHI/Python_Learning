#2. 基础概念：== 和 is 有什么区别？
#   为什么 a = 256; b = 256 时 a is b 通常是 True，而 a = 257; b = 257 时可能是 False？（提示：小整数缓存。）
'''
区别是：== 比较的是值是否相等，就像两个人长得一样，值相等自然就是true
       is 比较的是内存地址是否是相同的，就像比较两个人身份证号码是否一样

这是因为 Python 的小整数缓存机制。
为了优化性能，Python 在启动时就会自动创建并缓存从 -5 到 256 之间的整数对象。
所以当你赋值 256 时，它们指向的是内存里同一个缓存的整数对象。
而超出这个范围（比如 257），Python 会重新创建新的内存对象，所以 a 和 b 指向不同的内存地址，is 就会返回 False。
'''

